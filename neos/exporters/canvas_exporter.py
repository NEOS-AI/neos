def _markdown_to_html(md: str) -> str:
    """간단한 Markdown → HTML 변환 (외부 의존성 없음).

    지원 구문: h1-h3, **bold**, *italic*, `code`, [link](url),
              | table |, > blockquote, --- hr, 빈 줄 단락.
    """
    lines = md.split("\n")
    html_lines = []
    in_table = False
    in_code_block = False

    for line in lines:
        # 코드 블록
        if line.startswith("```"):
            if in_code_block:
                html_lines.append("</code></pre>")
                in_code_block = False
            else:
                html_lines.append("<pre><code>")
                in_code_block = True
            continue

        if in_code_block:
            html_lines.append(_escape(line))
            continue

        # 테이블
        if line.startswith("|") and line.endswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if not in_table:
                in_table = True
                html_lines.append("<table>")
                html_lines.append(
                    "<tr>" + "".join(f"<th>{_escape(c)}</th>" for c in cells) + "</tr>"
                )
            elif re.match(r"^\s*[-|: ]+$", line):
                pass  # separator row
            else:
                html_lines.append(
                    "<tr>" + "".join(f"<td>{_escape(c)}</td>" for c in cells) + "</tr>"
                )
            continue
        elif in_table:
            html_lines.append("</table>")
            in_table = False

        # 헤딩
        m = re.match(r"^(#{1,3})\s+(.+)$", line)
        if m:
            level = len(m.group(1))
            html_lines.append(f"<h{level}>{_inline(m.group(2))}</h{level}>")
            continue

        # 수평선
        if re.match(r"^-{3,}$", line.strip()):
            html_lines.append("<hr>")
            continue

        # 인용
        if line.startswith("> "):
            html_lines.append(f"<blockquote>{_inline(line[2:])}</blockquote>")
            continue

        # 목록
        if re.match(r"^\d+\.\s", line):
            html_lines.append(f"<p>{_inline(line)}</p>")
            continue

        # 빈 줄
        if not line.strip():
            html_lines.append("")
            continue

        html_lines.append(f"<p>{_inline(line)}</p>")

    if in_table:
        html_lines.append("</table>")
    if in_code_block:
        html_lines.append("</code></pre>")

    return "\n".join(html_lines)


def _safe_url(url: str) -> str:
    """http/https 스킴만 허용. 그 외는 '#'으로 대체 (CR-P6-02: javascript: URI 차단).

    구현은 `base.safe_url` 로 옮겼다 -- 이 수정이 canvas 에만 도착해 있었고
    html_exporter 는 뚫린 채였다(2026-09-05). 이름을 남기는 것은 이 모듈 안의
    호출부(`_inline`) 때문이고, 로직 사본은 하나다.
    """
    return safe_url(url)


def _inline(text: str) -> str:
    """인라인 마크다운(bold, italic, code, link) 처리."""
    # **bold**
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    # *italic*
    text = re.sub(r"\*(.+?)\*", r"<em>\1</em>", text)
    # `code`
    text = re.sub(r"`(.+?)`", lambda m: f"<code>{_escape(m.group(1))}</code>", text)
    # [text](url) — URL 스킴 검증 적용
    text = re.sub(
        r"\[(.+?)\]\((.+?)\)",
        lambda m: f'<a href="{_safe_url(m.group(2))}" target="_blank">{m.group(1)}</a>',
        text,
    )
    return text


def _build_charts_html(charts: list) -> str:
    if not charts:
        return ""
    items = []
    for c in charts:
        title = _escape(c.get("title", ""))
        alt = _escape(c.get("alt", title))
        b64 = c.get("image_b64", "")
        items.append(
            f'<div class="chart-item">'
            f'<img src="data:image/png;base64,{b64}" alt="{alt}">'
            f"<p>{title}</p></div>"
        )
    return f'<div class="section-charts"><h2>차트</h2>{"".join(items)}</div>'


def _build_diagram_html(mermaid_text: str) -> str:
    if not mermaid_text.strip():
        return ""
    # Mermaid는 HTML 엔티티를 그대로 파싱하므로 _escape() 사용 가능 (CR-P6-01: XSS 수정)
    safe = _escape(mermaid_text)
    return (
        f'<div class="section-diagram"><h2>소스 관계도</h2>'
        f'<div class="mermaid">{safe}</div></div>'
    )


def _escape(text: str) -> str:
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )
