class CanvasExporter(BaseExporter):
    """연구 리포트를 캔버스 HTML로 export.

    마크다운 구조 + 차트 이미지 + Mermaid 다이어그램을
    단일 self-contained HTML 파일로 묶는다.
    """

    async def export(
        self,
        report: ResearchReport,
        output_path: Optional[str] = None,
        **options,
    ) -> bytes:
        from neos.skills.builtin.canvas.renderers import (
            StructuredMarkdownRenderer,
            ChartRenderer,
            MermaidDiagramRenderer,
        )

        md_text = StructuredMarkdownRenderer().render(report)
        charts = await asyncio.to_thread(ChartRenderer().render, report)
        mermaid_text = MermaidDiagramRenderer().render(report)

        markdown_html = _markdown_to_html(md_text)
        charts_html = _build_charts_html(charts)
        diagram_html = _build_diagram_html(mermaid_text)

        html = CANVAS_HTML_TEMPLATE.format(
            title=_escape(report.query),
            markdown_html=markdown_html,
            charts_html=charts_html,
            diagram_html=diagram_html,
            session_id=report.session_id,
        )
        content = html.encode("utf-8")

        if output_path:
            with open(output_path, "wb") as f:
                f.write(content)

        return content

    def get_mime_type(self) -> str:
        return "text/html"

    def get_file_extension(self) -> str:
        return "html"


